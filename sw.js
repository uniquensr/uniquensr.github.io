const CACHE = `vinoha-${BUILD}`;
const OFFLINE_URL = '/offline.html';

/*
  The hero video is deliberately absent from every cache. It is 2 MB of
  decoration that a phone never even downloads, and putting it in a cache
  budget shared with the pages themselves would be a poor trade.
*/
const NEVER_CACHE = /^\/media\//;

/* Content-hashed filenames never change in place, so they can be trusted. */
const IMMUTABLE = /^\/(?:_next\/static|fonts)\//;

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      /*
        addAll() is all-or-nothing: one 404 and the whole install fails, which
        would leave the site with no worker at all. Each entry is added on its
        own so a single missing file costs only that file.
      */
      await Promise.all(
        PRECACHE.map((url) =>
          cache.add(new Request(url, { cache: 'reload' })).catch(() => {}),
        ),
      );
      /*
        No skipWaiting here on purpose. A worker that takes over the moment it
        installs would reload the page under whoever is using it — mid-form,
        mid-read. Instead it waits, the page notices and offers the update, and
        the swap happens on a click. On a first install there is no worker to
        wait for, so activation is immediate either way.
      */
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names.filter((n) => n.startsWith('vinoha-') && n !== CACHE).map((n) => caches.delete(n)),
      );
      await self.clients.claim();
    })(),
  );
});

/*
  The page asks for the swap rather than the worker taking it. A new worker
  waits until every tab is gone, and an installed home-screen app is almost
  never closed — so without this the update would never arrive.
*/
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;

  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  /* Same-origin only. A `mailto:` or `tel:` link is not ours to touch. */
  if (url.origin !== self.location.origin) return;
  if (NEVER_CACHE.test(url.pathname)) return;

  /*
    Pages: network first.

    A studio's site is a live document — a changed phone number or a new
    project has to reach people the moment it is uploaded. Cache-first would
    serve yesterday's page to anyone who had visited before. The cache is the
    fallback for a failed request, not the default answer.
  */
  if (request.mode === 'navigate') {
    event.respondWith(
      (async () => {
        try {
          const fresh = await fetch(request);
          const cache = await caches.open(CACHE);
          cache.put(request, fresh.clone());
          return fresh;
        } catch {
          const cached = await caches.match(request);
          if (cached) return cached;
          /* An unvisited page while offline still gets a real page, not the
             browser's dinosaur. */
          return (await caches.match(OFFLINE_URL)) ?? Response.error();
        }
      })(),
    );
    return;
  }

  /* Hashed assets: cache first, since the name changes when the bytes do. */
  if (IMMUTABLE.test(url.pathname)) {
    event.respondWith(
      (async () => {
        const cached = await caches.match(request);
        if (cached) return cached;
        const fresh = await fetch(request);
        if (fresh.ok) {
          const cache = await caches.open(CACHE);
          cache.put(request, fresh.clone());
        }
        return fresh;
      })(),
    );
    return;
  }

  /*
    Everything else — images, icons, the manifest: show what we have and
    refresh it in the background.
  */
  event.respondWith(
    (async () => {
      const cached = await caches.match(request);
      const network = fetch(request)
        .then((fresh) => {
          if (fresh.ok) {
            caches.open(CACHE).then((cache) => cache.put(request, fresh.clone()));
          }
          return fresh;
        })
        .catch(() => null);
      return cached ?? (await network) ?? Response.error();
    })(),
  );
});
